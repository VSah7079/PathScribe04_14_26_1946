#!/usr/bin/env node
// scripts/generate-security-headers.mjs
// ─────────────────────────────────────────────────────────────────────────────
// Batch 503 (PS-474): writes every hosting option's header config from
// deploy/security-headers/securityHeaders.mjs and an origins file.
//
//   node scripts/generate-security-headers.mjs [origins.json] [outDir]
//
// Defaults: deploy/security-headers/origins.example.json → deploy/security-headers/generated/.
// With origins.demo.json it also refreshes the root vercel.json headers.
// Outputs: nginx.conf (include in the server block), web.config (IIS, and
// Azure App Service on Windows), staticwebapp.config.json (Azure Static Web
// Apps), azure-front-door-rules.json (Front Door rule set, response headers),
// headers.txt (plain list for any other host).
// ─────────────────────────────────────────────────────────────────────────────

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { securityHeaders, originsWithRuntimeConfig } from '../deploy/security-headers/securityHeaders.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const originsPath = resolve(ROOT, process.argv[2] ?? 'deploy/security-headers/origins.example.json');
const outDir = resolve(ROOT, process.argv[3] ?? 'deploy/security-headers/generated');
// Batch 547: --runtime-config <config.json> adds the addresses the deployment's config.json sets.
const runtimeFlag = process.argv.indexOf('--runtime-config');
const runtimeConfig = runtimeFlag > 0 ? JSON.parse(readFileSync(resolve(ROOT, process.argv[runtimeFlag + 1]), 'utf8')) : {};
const origins = originsWithRuntimeConfig(JSON.parse(readFileSync(originsPath, 'utf8')), runtimeConfig);
const headers = securityHeaders(origins);
const xmlAttr = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const banner = 'Generated by scripts/generate-security-headers.mjs from deploy/security-headers/securityHeaders.mjs and this deployment\'s origins file (Batch 503, PS-474). Edit the origins file and re-run; do not edit this file.';

export function renderNginx(h) {
  return [`# ${banner}`, '# Include inside the server { } block that serves PathScribe.', ...h.map(([n, v]) => `add_header ${n} "${v.replace(/"/g, '\\"')}" always;`), ''].join('\n');
}
export function renderWebConfig(h) {
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${banner} -->`,
    '<!-- IIS, and Azure App Service on Windows. Merge into the site web.config. -->',
    '<configuration>', '  <system.webServer>', '    <httpProtocol>', '      <customHeaders>',
    '        <remove name="X-Powered-By" />',
    ...h.map(([n, v]) => `        <add name="${n}" value="${xmlAttr(v)}" />`),
    '      </customHeaders>', '    </httpProtocol>', '  </system.webServer>', '</configuration>', '',
  ].join('\n');
}
export function renderStaticWebApp(h) {
  return `${JSON.stringify({ _comment: banner, navigationFallback: { rewrite: '/index.html', exclude: ['/assets/*', '/fonts/*', '/help/*', '*.{png,jpg,svg,ico,webp,css,js,json,wasm}'] }, globalHeaders: Object.fromEntries(h) }, null, 2)}\n`;
}
export function renderFrontDoor(h) {
  return `${JSON.stringify({
    _comment: `${banner} Azure Front Door Standard/Premium: a rule set with one rule whose actions overwrite these response headers; attach it to the PathScribe route.`,
    ruleSet: 'PathScribeSecurityHeaders',
    rules: [{ name: 'SecurityHeaders', order: 1, conditions: [], actions: h.map(([n, v]) => ({ name: 'ModifyResponseHeader', parameters: { headerAction: 'Overwrite', headerName: n, value: v } })) }],
  }, null, 2)}\n`;
}
export function renderVercelHeaders(h) {
  return [{ source: '/(.*)', headers: h.map(([key, value]) => ({ key, value })) }];
}
export function renderPlain(h) {
  return [`# ${banner}`, ...h.map(([n, v]) => `${n}: ${v}`), ''].join('\n');
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, 'nginx.conf'), renderNginx(headers));
  writeFileSync(resolve(outDir, 'web.config'), renderWebConfig(headers));
  writeFileSync(resolve(outDir, 'staticwebapp.config.json'), renderStaticWebApp(headers));
  writeFileSync(resolve(outDir, 'azure-front-door-rules.json'), renderFrontDoor(headers));
  writeFileSync(resolve(outDir, 'headers.txt'), renderPlain(headers));
  if (basename(originsPath) === 'origins.demo.json') {
    const vercelPath = resolve(ROOT, 'vercel.json');
    const vercel = JSON.parse(readFileSync(vercelPath, 'utf8'));
    vercel.headers = renderVercelHeaders(headers);
    writeFileSync(vercelPath, `${JSON.stringify(vercel, null, 2)}\n`);
  }
  console.log(`Wrote ${headers.length} headers for ${basename(originsPath)} to ${outDir}`);
}
