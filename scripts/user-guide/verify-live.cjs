#!/usr/bin/env node
/* Batch 667: opens every screen the User Guide claims, in a real browser on the demo data, and
   (1) records whether it opened (not refused / not an error page),
   (2) lists buttons, tabs, headings and column titles that are visible on opening but appear nowhere in that article,
   (3) saves the "-overview" screenshot named in docs/user-guide/MISSING_CAPTURES.md (only if the png is missing),
   (4) writes docs/user-guide/LIVE_CHECK.md.
   Run with the app serving on A11Y_PORT (default 5179):  node scripts/user-guide/verify-live.cjs [--no-shots] */
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const G = path.join(ROOT, 'docs/user-guide');
const PORT = process.env.A11Y_PORT || 5179;
const NOSHOTS = process.argv.includes('--no-shots');
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'public/help/user-guide/manifest.json'), 'utf8'));
const norm = s => s.toLowerCase().replace(/\{\{[^}]*\}\}/g, ' ').replace(/[^a-z0-9]+/g, ' ').trim();
const read = f => fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
const articleText = slug => read(path.join(G, 'src', slug + '.md')) + read(path.join(G, 'src', slug, 'index.md'));
const missing = read(path.join(G, 'MISSING_CAPTURES.md'));
const overviewIds = {}; // article slug -> capture id ending -overview
for (const m of missing.matchAll(/\| `([^`]+-overview)` \| `([^`]+)` \|/g)) overviewIds[m[2]] = m[1];
const PARAM = { ':caseId': 'S26-4408', ':id': 'S26-4408', ':accessionNumber': 'S26-4408' };

(async () => {
  const launch = () => chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM || undefined, args: ['--disable-dev-shm-usage', '--disable-gpu'] });
  let browser = await launch();
  const fresh = async () => {
    const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 } });
    await ctx.addInitScript(() => {
      try {
        if (!localStorage.getItem('pathscribe-user')) {
          localStorage.setItem('pathscribe-user', JSON.stringify({ id: 'PATH-001', name: 'Pete Nimmo', role: 'superadmin' }));
          localStorage.setItem('pathscribe_scan_station_prompted', '1');
        }
      } catch (e) { /* none */ }
    });
    return ctx;
  };
  const rows = [];
  for (const a of manifest.articles) {
    for (const route of a.routes) {
      let url = route.replace(/:\w+/g, m => PARAM[m] || m);
      if (/:\w+/.test(url)) { rows.push({ slug: a.slug, route, status: 'skipped (needs a real id)' }); continue; }
      let ctx;
      try {
        ctx = await fresh();
        const page = await ctx.newPage();
        await page.goto(`http://localhost:${PORT}${url}`, { waitUntil: 'domcontentloaded' });
        await page.waitForTimeout(3500);
        await page.locator('.ps-scan-prompt-skip').click({ timeout: 500 }).catch(() => {});
        const denied = await page.locator('.ps-screen-denied').count();
        const unavailable = await page.locator('.ps-case-unavailable').count();
        const errored = await page.locator('text=/something went wrong|unexpected error/i').count();
        const texts = await page.evaluate(() => {
          const out = new Set();
          document.querySelectorAll('button, [role=tab], [role=button], th, h1, h2, h3, h4, label, a, legend, summary').forEach(e => {
            if (!(e.offsetWidth || e.offsetHeight)) return;
            const t = (e.getAttribute('aria-label') || e.innerText || '').replace(/\s+/g, ' ').trim();
            if (t) out.add(t);
          });
          return [...out];
        });
        const hay = ' ' + norm(articleText(a.slug)) + ' ';
        const gaps = texts.filter(t => t.length >= 3 && t.length <= 40 && !/\d{3,}/.test(t) && norm(t).length >= 3 && !hay.includes(' ' + norm(t) + ' '));
        let shot = '';
        const id = overviewIds[a.slug];
        if (id && !NOSHOTS && !denied && !unavailable && !errored && route === a.routes[0]) {
          const f = path.join(G, 'img', id + '.png');
          if (!fs.existsSync(f)) { fs.mkdirSync(path.dirname(f), { recursive: true }); await page.screenshot({ path: f }); shot = id; }
        }
        rows.push({ slug: a.slug, route, status: denied ? 'REFUSED' : unavailable ? 'UNAVAILABLE' : errored ? 'ERROR PAGE' : 'opened', visible: texts.length, gaps, shot });
        await ctx.close();
      } catch (e) {
        rows.push({ slug: a.slug, route, status: 'FAILED: ' + String(e.message).split('\n')[0] });
        try { await ctx.close(); } catch (e2) { /* gone */ }
        try { await browser.close(); } catch (e3) { /* gone */ }
        browser = await launch();
      }
    }
  }
  await browser.close();
  const bad = rows.filter(r => !['opened'].includes(r.status) && !r.status.startsWith('skipped'));
  let md = `# Live check of the User Guide (generated by scripts/user-guide/verify-live.cjs)\n\nEach screen the guide claims was opened in Chromium on the demo data, signed in as a superadmin.\n\n`;
  md += `- Screens tried: ${rows.length}; opened: ${rows.filter(r => r.status === 'opened').length}; not opened: ${bad.length}; skipped: ${rows.filter(r => r.status.startsWith('skipped')).length}\n`;
  md += `- Screenshots saved: ${rows.filter(r => r.shot).length}\n- Visible buttons, tabs, headings and column titles that the article never mentions: ${rows.reduce((n, r) => n + (r.gaps ? r.gaps.length : 0), 0)}\n\n`;
  if (bad.length) { md += `## Screens that did not open as the guide says\n\n| Article | Address | Result |\n|---|---|---|\n` + bad.map(r => `| ${r.slug} | \`${r.route}\` | ${r.status} |`).join('\n') + '\n\n'; }
  md += `## Visible on opening but not in the article\n\n`;
  for (const r of rows.filter(r => r.gaps && r.gaps.length)) md += `**${r.slug}** (\`${r.route}\`): ${r.gaps.map(g => '"' + g + '"').join(', ')}\n\n`;
  fs.writeFileSync(path.join(G, 'LIVE_CHECK.md'), md);
  fs.writeFileSync('/tmp/claude-0/live_check.json', JSON.stringify(rows, null, 1));
  console.log(md.split('\n').slice(0, 8).join('\n'));
})();
