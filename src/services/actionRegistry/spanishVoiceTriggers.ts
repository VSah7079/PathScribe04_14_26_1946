/** Adds the Spanish phrases to actions that have none; leaves edited ones alone. */
export function withSpanishVoiceTriggers(actions: SystemAction[]): SystemAction[] {
  return actions.map(a => {
    const spanish = SPANISH_VOICE_TRIGGERS[a.id];
    if (!spanish || a.voiceTriggersByLanguage?.es?.length) return a;
    return { ...a, voiceTriggersByLanguage: { ...a.voiceTriggersByLanguage, es: [...spanish] } };
  });
}
